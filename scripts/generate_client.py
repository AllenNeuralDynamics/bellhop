"""Generate httpx client methods from the live FastAPI app.

Reuses the real ``bellhop_models`` classes directly (no regenerated models) by
introspecting ``bellhop.api.app`` rather than the serialized OpenAPI spec.

Run via ``make generate-client``. Client construction, lifecycle, and the
streaming endpoint live in ``bellhop_client._base`` and are not generated.
"""

from __future__ import annotations

import typing
from pathlib import Path

from fastapi.routing import APIRoute
from jinja2 import Template
from pydantic import BaseModel

from bellhop.api import app

CLIENT_DIR = Path(__file__).resolve().parents[1] / "packages/bellhop-client/src/bellhop_client"

# Endpoints provided by the hand-written base instead of being generated.
SKIP = {"stream_execution_logs"}

MODULE_TEMPLATE = Template(
    '''"""Generated by scripts/generate_client.py. Do not edit by hand."""

{{ imports }}


class {{ class_name }}({{ base_class }}):
{% for op in operations %}
    {{ "async def" if is_async else "def" }} {{ op.name }}({{ op.args }}) -> {{ op.return_type }}:
        response = {{ "await " if is_async else "" }}{{ op.call }}
        response.raise_for_status()
{% if op.parse %}
        return {{ op.parse }}
{% endif %}

{% endfor %}
''',
    trim_blocks=True,
    lstrip_blocks=True,
)


class Imports:
    def __init__(self) -> None:
        self.plain: set[str] = set()
        self.frm: dict[str, set[str]] = {}

    def add_plain(self, module: str) -> None:
        self.plain.add(module)

    def add_from(self, module: str, name: str) -> None:
        self.frm.setdefault(module, set()).add(name)

    def render(self) -> str:
        groups: list[str] = []
        if self.plain:
            groups.append("\n".join(f"import {m}" for m in sorted(self.plain)))
        if self.frm:
            groups.append(
                "\n".join(f"from {mod} import {', '.join(sorted(self.frm[mod]))}" for mod in sorted(self.frm))
            )
        return "\n\n".join(groups)


def _is_model(tp: object) -> bool:
    return isinstance(tp, type) and issubclass(tp, BaseModel)


def render_type(tp: object, imports: Imports) -> str:
    if tp is None or tp is type(None):
        return "None"
    origin = typing.get_origin(tp)
    if origin is not None:
        inner = ", ".join(render_type(a, imports) for a in typing.get_args(tp))
        name = {list: "list", dict: "dict", tuple: "tuple", set: "set"}.get(origin, getattr(origin, "__name__", ""))
        return f"{name}[{inner}]"
    module = getattr(tp, "__module__", "")
    name = getattr(tp, "__name__", str(tp))
    if module == "uuid":
        imports.add_plain("uuid")
        return f"uuid.{name}"
    if module == "builtins":
        return name
    if module.startswith("bellhop_models"):
        imports.add_from(module, name)
    return name


def parse_expr(response_model: object, imports: Imports) -> str | None:
    """Expression converting ``response`` into the return value, or None for no body."""
    if response_model is None or response_model is type(None):
        return None
    if typing.get_origin(response_model) is list:
        (arg,) = typing.get_args(response_model)
        if _is_model(arg):
            imports.add_from(arg.__module__, arg.__name__)
            return f"[{arg.__name__}.model_validate(item) for item in response.json()]"
        return "response.json()"
    if _is_model(response_model):
        imports.add_from(response_model.__module__, response_model.__name__)
        return f"{response_model.__name__}.model_validate(response.json())"
    if getattr(response_model, "__module__", "") == "uuid":
        imports.add_plain("uuid")
        return f"uuid.{response_model.__name__}(response.json())"
    return "response.json()"


def build_operation(route: APIRoute, imports: Imports) -> dict[str, str | None]:
    """Introspect one route into template data (independent of sync/async)."""
    hints = typing.get_type_hints(route.endpoint)
    dep = route.dependant
    path_names = sorted((p.name for p in dep.path_params), key=lambda n: route.path.find("{" + n + "}"))
    query_names = [p.name for p in dep.query_params]
    body_names = [p.name for p in dep.body_params]

    args = ["self", *(f"{n}: {render_type(hints[n], imports)}" for n in (*path_names, *body_names, *query_names))]
    url = f'f"{route.path}"' if "{" in route.path else f'"{route.path}"'

    kwargs: list[str] = []
    if query_names:
        kwargs.append("params={" + ", ".join(f'"{n}": {n}' for n in query_names) + "}")
    if body_names:
        if len(body_names) == 1 and _is_model(hints[body_names[0]]):
            kwargs.append(f'json={body_names[0]}.model_dump(mode="json")')
        elif len(body_names) == 1:
            kwargs.append(f"json={body_names[0]}")
        else:
            kwargs.append("json={" + ", ".join(f'"{n}": {n}' for n in body_names) + "}")

    verb = next(m for m in route.methods if m not in {"HEAD", "OPTIONS"}).lower()
    if body_names and verb == "get":
        call = f'self._client.request("GET", {", ".join([url, *kwargs])})'
    else:
        call = f"self._client.{verb}({', '.join([url, *kwargs])})"

    return {
        "name": route.name,
        "args": ", ".join(args),
        "return_type": render_type(route.response_model, imports),
        "call": call,
        "parse": parse_expr(route.response_model, imports),
    }


def generate(*, is_async: bool) -> str:
    imports = Imports()
    base = "AsyncClientBase" if is_async else "SyncClientBase"
    cls = "AsyncBellhopClient" if is_async else "BellhopClient"
    imports.add_from("bellhop_client._base", base)

    operations = [
        build_operation(route, imports)
        for route in app.routes
        if isinstance(route, APIRoute) and route.name not in SKIP
    ]
    return MODULE_TEMPLATE.render(
        imports=imports.render(),
        class_name=cls,
        base_class=base,
        operations=operations,
        is_async=is_async,
    )


def main() -> None:
    (CLIENT_DIR / "sync_client.py").write_text(generate(is_async=False))
    (CLIENT_DIR / "async_client.py").write_text(generate(is_async=True))
    print("Wrote client.py and async_client.py")


if __name__ == "__main__":
    main()
